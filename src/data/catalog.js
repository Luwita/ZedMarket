// Unit price for a quantity, taking wholesale tiers into account.
export function unitPrice(product, qty) {
  let price = product.price;
  for (const tier of [...product.tiers].sort((a, b) => a.min - b.min)) {
    if (qty >= tier.min) price = tier.price;
  }
  return price;
}

